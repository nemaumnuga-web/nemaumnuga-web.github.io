def marks_over(T, extra):
    """Cyrillic letters with accents: Ё ё Й й."""
    out = {}
    for cp, base_cp, kind in extra:
        st, w = T[base_cp] if base_cp in T else LAT[chr(base_cp)]
        top = CAP + 40 if base_cp < 0x430 and chr(base_cp).isupper() else XH + 40
        cx = w / 2.0
        if kind == "diaeresis":
            st = st + [D(cx - 62, top + 60, 1.0), D(cx + 62, top + 60, 1.0)]
        else:
            st = st + [PS(arc(cx, top + 100, 90, 90, 200, 340, 12))]
        out[cp] = (st, w)
    return out


